//! Keyboard capture with a `CGEventTap`.
//!
//! The WM swallows bound Cmd combinations globally and lets everything else
//! through. The tap is installed at the HID/session level with
//! `kCGEventTapOptionDefault` (active tap) so the callback can return `NULL` to
//! swallow an event.
//!
//! Two failure modes matter:
//!
//! * `kCGEventTapDisabledByTimeout` / `kCGEventTapDisabledByUserInput`: the
//!   system disables a slow tap. The callback re-enables it immediately and
//!   logs a warning. Keep the callback allocation-free and fast.
//! * Secure Event Input (password fields, some terminals): the tap receives no
//!   key events at all. cosmicMac documents a Carbon `RegisterEventHotKey`
//!   fallback for the most important bindings; it is intentionally not wired
//!   up in the platform crate yet because Carbon hotkeys cannot swallow events
//!   and need a different action path in the WM.
//!
//! Modifier changes (`kCGEventFlagsChanged`) are reported to the handler as
//! well, so the WM can recognise a Super (Command) tap, but they are **never**
//! swallowed: an app must always see its modifier state change.
//!
//! Accessibility is required for the tap to see key events from other apps.
//!
//! [`MouseTap`] is a second, **listen-only** tap for the left mouse button
//! (down, dragged, up). It never delays or swallows a click; the WM uses it
//! to tell a title-bar drag from other window moves (drag-to-stack).

use std::ffi::c_void;

use objc2_core_foundation::{
    CFMachPort, CFRetained, CFRunLoop, CFRunLoopSource, kCFRunLoopCommonModes,
};
use objc2_core_graphics::{
    CGEvent, CGEventField, CGEventFlags, CGEventSource, CGEventSourceStateID, CGEventTapLocation,
    CGEventTapOptions, CGEventTapPlacement, CGEventType,
};

use crate::error::{PlatformError, Result};
use crate::geometry::Point;

/// A key binding the tap should swallow.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HotkeySpec {
    /// Virtual key code (`kVK_*`, e.g. 16 = Y).
    pub keycode: u16,
    /// Required modifier bits (`CGEventFlags`).
    pub modifiers: u64,
}

impl HotkeySpec {
    /// Command modifier mask (`kCGEventFlagMaskCommand`).
    pub const MASK_COMMAND: u64 = 1 << 20;
    /// Shift modifier mask (`kCGEventFlagMaskShift`).
    pub const MASK_SHIFT: u64 = 1 << 17;
    /// Option modifier mask (`kCGEventFlagMaskAlternate`).
    pub const MASK_OPTION: u64 = 1 << 19;
    /// Control modifier mask (`kCGEventFlagMaskControl`).
    pub const MASK_CONTROL: u64 = 1 << 18;
    /// Fn / Globe modifier mask (`kCGEventFlagMaskSecondaryFn`). Not part of
    /// [`KeyEvent::modifiers`]: macOS also sets it on arrow and function keys.
    pub const MASK_FN: u64 = 1 << 23;

    /// Create a spec.
    pub const fn new(keycode: u16, modifiers: u64) -> Self {
        Self { keycode, modifiers }
    }
}

/// A key event observed by the tap.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KeyEvent {
    /// Virtual key code.
    pub keycode: u16,
    /// Raw `CGEventFlags`.
    pub flags: u64,
    /// True for key down, false for key up.
    pub is_key_down: bool,
    /// True for a key-down generated by holding the key (autorepeat).
    pub is_repeat: bool,
    /// True for a modifier change (`kCGEventFlagsChanged`): `keycode` is the
    /// modifier key (55/54 for left/right Command), `flags` the modifier
    /// state after the change, and `is_key_down` is false. The tap never
    /// swallows these, whatever the handler returns.
    pub is_flags_changed: bool,
}

impl KeyEvent {
    /// Modifier bits with device-independent masks removed (caps lock, fn, ...).
    pub fn modifiers(&self) -> u64 {
        self.flags
            & (HotkeySpec::MASK_COMMAND
                | HotkeySpec::MASK_SHIFT
                | HotkeySpec::MASK_OPTION
                | HotkeySpec::MASK_CONTROL)
    }
}

/// Callback: return `true` to swallow the event, `false` to pass it through.
pub type TapHandler = Box<dyn Fn(KeyEvent) -> bool + Send + 'static>;

struct TapContext {
    handler: TapHandler,
    swallow: Vec<HotkeySpec>,
    tap: *mut c_void,
}

unsafe extern "C-unwind" fn tap_callback(
    _proxy: objc2_core_graphics::CGEventTapProxy,
    event_type: CGEventType,
    event: std::ptr::NonNull<CGEvent>,
    user_info: *mut c_void,
) -> *mut CGEvent {
    if user_info.is_null() {
        return event.as_ptr();
    }
    // SAFETY: user_info points to the TapContext owned by EventTap.
    let context = unsafe { &mut *(user_info as *mut TapContext) };

    if reenable_if_disabled(event_type, context.tap) {
        return event.as_ptr();
    }

    let is_key_down = event_type == CGEventType::KeyDown;
    let is_key_up = event_type == CGEventType::KeyUp;
    let is_flags_changed = event_type == CGEventType::FlagsChanged;
    if !is_key_down && !is_key_up && !is_flags_changed {
        return event.as_ptr();
    }

    // SAFETY: valid event reference.
    let keycode = unsafe {
        CGEvent::integer_value_field(Some(event.as_ref()), CGEventField::KeyboardEventKeycode)
    } as u16;
    // SAFETY: valid event reference.
    let flags = unsafe { CGEvent::flags(Some(event.as_ref())) }.0;
    // SAFETY: valid event reference.
    let is_repeat = unsafe {
        CGEvent::integer_value_field(Some(event.as_ref()), CGEventField::KeyboardEventAutorepeat)
    } != 0;

    let key = KeyEvent {
        keycode,
        flags,
        is_key_down,
        is_repeat: is_repeat && !is_flags_changed,
        is_flags_changed,
    };
    if is_flags_changed {
        // Observe only: swallowing a modifier change would leave apps with a
        // stuck (or missing) modifier.
        (context.handler)(key);
        return event.as_ptr();
    }
    let matched = context
        .swallow
        .iter()
        .any(|spec| spec.keycode == key.keycode && key.modifiers() == spec.modifiers);

    if matched && is_key_down {
        (context.handler)(key);
        return std::ptr::null_mut(); // swallow
    }
    if matched && is_key_up {
        // Swallow the matching key-up too, otherwise the app sees a stuck key.
        return std::ptr::null_mut();
    }
    if (context.handler)(key) {
        return std::ptr::null_mut();
    }
    event.as_ptr()
}

/// Re-enables `tap` when `event_type` says the system disabled it
/// (`kCGEventTapDisabledByTimeout` / `ByUserInput`); returns whether it did.
fn reenable_if_disabled(event_type: CGEventType, tap: *mut c_void) -> bool {
    if event_type != CGEventType::TapDisabledByTimeout
        && event_type != CGEventType::TapDisabledByUserInput
    {
        return false;
    }
    log::warn!(
        "CGEventTap disabled by the system ({}); re-enabling",
        if event_type == CGEventType::TapDisabledByTimeout {
            "timeout"
        } else {
            "user input"
        }
    );
    if !tap.is_null() {
        // SAFETY: tap is the CFMachPort the calling callback belongs to.
        unsafe { CGEvent::tap_enable(&*(tap as *const CFMachPort), true) };
    }
    true
}

/// An installed active event tap.
pub struct EventTap {
    tap: CFRetained<CFMachPort>,
    source: CFRetained<CFRunLoopSource>,
    context: *mut TapContext,
}

// The tap is only used from the run loop thread; the raw pointers are immutable
// for the lifetime of the object.
unsafe impl Send for EventTap {}

impl EventTap {
    /// Create and enable a tap that swallows `swallow` and reports every other
    /// key event to `handler`.
    ///
    /// `handler` is called for every key down/up, including swallowed ones,
    /// and for every modifier change. Returning `true` from the handler also
    /// swallows a key down/up; modifier changes always pass through.
    pub fn new(swallow: Vec<HotkeySpec>, handler: TapHandler) -> Result<Self> {
        let context = Box::into_raw(Box::new(TapContext {
            handler,
            swallow,
            tap: std::ptr::null_mut(),
        }));

        let mask: u64 = (1u64 << CGEventType::KeyDown.0)
            | (1u64 << CGEventType::KeyUp.0)
            | (1u64 << CGEventType::FlagsChanged.0);

        // SAFETY: callback and context outlive the tap (released in Drop).
        let tap = unsafe {
            CGEvent::tap_create(
                CGEventTapLocation::SessionEventTap,
                CGEventTapPlacement::HeadInsertEventTap,
                CGEventTapOptions::Default,
                mask,
                Some(tap_callback),
                context.cast(),
            )
        }
        .ok_or_else(|| {
            // SAFETY: reclaim the context because the tap was never created.
            unsafe { drop(Box::from_raw(context)) };
            PlatformError::Other(
                "CGEventTapCreate failed. Accessibility (and Input Monitoring on some macOS \
                 versions) must be granted to this binary."
                    .into(),
            )
        })?;

        let tap_ptr = CFRetained::as_ptr(&tap).as_ptr();
        // SAFETY: context is still alive.
        unsafe { (*context).tap = tap_ptr.cast() };

        let source = CFMachPort::new_run_loop_source(None, Some(&tap), 0)
            .ok_or_else(|| PlatformError::Other("CFMachPortCreateRunLoopSource failed".into()))?;

        let run_loop = CFRunLoop::current()
            .ok_or_else(|| PlatformError::Other("no current CFRunLoop".into()))?;
        run_loop.add_source(Some(&source), unsafe { kCFRunLoopCommonModes });
        CGEvent::tap_enable(&tap, true);

        Ok(Self {
            tap,
            source,
            context,
        })
    }

    /// Whether the tap is currently enabled.
    pub fn is_enabled(&self) -> bool {
        CGEvent::tap_is_enabled(&self.tap)
    }

    /// Enable or disable the tap.
    pub fn set_enabled(&self, enabled: bool) {
        CGEvent::tap_enable(&self.tap, enabled);
    }

    /// The run-loop source, in case the caller wants to add it to another loop.
    pub fn run_loop_source(&self) -> &CFRunLoopSource {
        &self.source
    }

    /// Add the tap's source to the calling thread's run loop.
    pub fn add_to_current_run_loop(&self) -> Result<()> {
        let run_loop = CFRunLoop::current()
            .ok_or_else(|| PlatformError::Other("no current CFRunLoop".into()))?;
        run_loop.add_source(Some(&self.source), unsafe { kCFRunLoopCommonModes });
        Ok(())
    }
}

impl Drop for EventTap {
    fn drop(&mut self) {
        CGEvent::tap_enable(&self.tap, false);
        // Invalidate the run-loop source (removing it from every run loop) and
        // the mach port first, so no event still queued can reach
        // `tap_callback` with the context freed below.
        self.source.invalidate();
        self.tap.invalidate();
        // SAFETY: the source and port are invalidated, so the callback can no
        // longer run; the CF objects themselves are released by their own
        // Drop. Reclaim our callback context.
        unsafe { drop(Box::from_raw(self.context)) };
    }
}

/// What the left mouse button did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MouseEventKind {
    /// `kCGEventLeftMouseDown`.
    Down,
    /// `kCGEventLeftMouseDragged` (moved with the button held).
    Dragged,
    /// `kCGEventLeftMouseUp`.
    Up,
}

/// A left-button event seen by [`MouseTap`].
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MouseEvent {
    /// Down, dragged or up.
    pub kind: MouseEventKind,
    /// Pointer location in global top-left coordinates (the AX space).
    pub location: Point,
}

/// Callback for [`MouseTap`]. Runs on the tap's run-loop thread; keep it
/// short (send to a channel).
pub type MouseHandler = Box<dyn Fn(MouseEvent) + Send + 'static>;

/// [`MouseTap`] forwards at most one dragged event per interval (~30 Hz);
/// down and up always pass.
pub const DRAG_INTERVAL: std::time::Duration = std::time::Duration::from_millis(33);

struct MouseContext {
    handler: MouseHandler,
    tap: *mut c_void,
    last_drag: Option<std::time::Instant>,
}

unsafe extern "C-unwind" fn mouse_callback(
    _proxy: objc2_core_graphics::CGEventTapProxy,
    event_type: CGEventType,
    event: std::ptr::NonNull<CGEvent>,
    user_info: *mut c_void,
) -> *mut CGEvent {
    if user_info.is_null() {
        return event.as_ptr();
    }
    // SAFETY: user_info points to the MouseContext owned by MouseTap.
    let context = unsafe { &mut *(user_info as *mut MouseContext) };
    if reenable_if_disabled(event_type, context.tap) {
        return event.as_ptr();
    }
    let kind = match event_type {
        CGEventType::LeftMouseDown => MouseEventKind::Down,
        CGEventType::LeftMouseDragged => MouseEventKind::Dragged,
        CGEventType::LeftMouseUp => MouseEventKind::Up,
        _ => return event.as_ptr(),
    };
    let now = std::time::Instant::now();
    if kind == MouseEventKind::Dragged {
        if context
            .last_drag
            .is_some_and(|last| now.duration_since(last) < DRAG_INTERVAL)
        {
            return event.as_ptr();
        }
        context.last_drag = Some(now);
    } else {
        context.last_drag = None;
    }
    // SAFETY: valid event reference.
    let location = unsafe { CGEvent::location(Some(event.as_ref())) };
    (context.handler)(MouseEvent {
        kind,
        location: Point::new(location.x, location.y),
    });
    event.as_ptr()
}

/// An installed listen-only tap for the left mouse button.
///
/// Listen-only (`kCGEventTapOptionListenOnly`): it cannot delay or swallow
/// events. Dragged events are throttled to [`DRAG_INTERVAL`].
pub struct MouseTap {
    tap: CFRetained<CFMachPort>,
    source: CFRetained<CFRunLoopSource>,
    context: *mut MouseContext,
}

// Only used from the run loop thread, like `EventTap`.
unsafe impl Send for MouseTap {}

impl MouseTap {
    /// Create and enable the tap on the calling thread's run loop.
    pub fn new(handler: MouseHandler) -> Result<Self> {
        let context = Box::into_raw(Box::new(MouseContext {
            handler,
            tap: std::ptr::null_mut(),
            last_drag: None,
        }));
        let mask: u64 = (1u64 << CGEventType::LeftMouseDown.0)
            | (1u64 << CGEventType::LeftMouseDragged.0)
            | (1u64 << CGEventType::LeftMouseUp.0);
        // SAFETY: callback and context outlive the tap (released in Drop).
        let tap = unsafe {
            CGEvent::tap_create(
                CGEventTapLocation::SessionEventTap,
                CGEventTapPlacement::TailAppendEventTap,
                CGEventTapOptions::ListenOnly,
                mask,
                Some(mouse_callback),
                context.cast(),
            )
        }
        .ok_or_else(|| {
            // SAFETY: reclaim the context because the tap was never created.
            unsafe { drop(Box::from_raw(context)) };
            PlatformError::Other("CGEventTapCreate (mouse, listen-only) failed".into())
        })?;
        let tap_ptr = CFRetained::as_ptr(&tap).as_ptr();
        // SAFETY: context is still alive.
        unsafe { (*context).tap = tap_ptr.cast() };
        let source = CFMachPort::new_run_loop_source(None, Some(&tap), 0).ok_or_else(|| {
            tap.invalidate();
            // SAFETY: the port is invalidated, so the callback cannot run.
            unsafe { drop(Box::from_raw(context)) };
            PlatformError::Other("CFMachPortCreateRunLoopSource failed".into())
        })?;
        let run_loop = CFRunLoop::current()
            .ok_or_else(|| PlatformError::Other("no current CFRunLoop".into()))?;
        run_loop.add_source(Some(&source), unsafe { kCFRunLoopCommonModes });
        CGEvent::tap_enable(&tap, true);
        Ok(Self {
            tap,
            source,
            context,
        })
    }

    /// Whether the tap is currently enabled.
    pub fn is_enabled(&self) -> bool {
        CGEvent::tap_is_enabled(&self.tap)
    }
}

impl Drop for MouseTap {
    fn drop(&mut self) {
        CGEvent::tap_enable(&self.tap, false);
        // As for `EventTap`: invalidate first so no queued event reaches the
        // callback after the context is freed.
        self.source.invalidate();
        self.tap.invalidate();
        // SAFETY: the callback can no longer run.
        unsafe { drop(Box::from_raw(self.context)) };
    }
}

/// Post a synthetic left-button event at `location` (global top-left) to the
/// HID tap, as a real mouse does. For scripted drag tests
/// (`send-key --drag`); needs the Accessibility grant like every posted
/// event.
pub fn post_left_mouse(kind: MouseEventKind, location: Point) -> Result<()> {
    let event_type = match kind {
        MouseEventKind::Down => CGEventType::LeftMouseDown,
        MouseEventKind::Dragged => CGEventType::LeftMouseDragged,
        MouseEventKind::Up => CGEventType::LeftMouseUp,
    };
    let event = CGEvent::new_mouse_event(
        None,
        event_type,
        objc2_core_foundation::CGPoint::new(location.x, location.y),
        objc2_core_graphics::CGMouseButton::Left,
    )
    .ok_or_else(|| PlatformError::Other("CGEventCreateMouseEvent failed".into()))?;
    CGEvent::post(CGEventTapLocation::HIDEventTap, Some(&event));
    Ok(())
}

/// Seconds since the most recent mouse-button press, scroll or key press in
/// the login session, whichever came last (`CGEventSourceSecondsSinceLastEventType`
/// over the combined session state, so posted events count too).
///
/// The WM's Super-tap detector compares this with how long Command was
/// held: it sees clicks without adding mouse events to the active tap, and
/// key presses the tap misses (Secure Event Input hides key events from taps
/// but not from this counter). Safe from any thread.
pub fn seconds_since_click_scroll_or_key() -> f64 {
    [
        CGEventType::LeftMouseDown,
        CGEventType::RightMouseDown,
        CGEventType::OtherMouseDown,
        CGEventType::ScrollWheel,
        CGEventType::KeyDown,
    ]
    .into_iter()
    .map(|event_type| {
        CGEventSource::seconds_since_last_event_type(
            CGEventSourceStateID::CombinedSessionState,
            event_type,
        )
    })
    .fold(f64::INFINITY, f64::min)
}

/// Post a synthetic modifier change (`kCGEventFlagsChanged`) at the HID
/// level, as pressing (`flags` holds the modifier) or releasing (`flags` 0)
/// the modifier key `keycode` does. For scripted tests of the Super tap
/// (`send-key --tap-super`); needs the Accessibility grant like every posted
/// event.
pub fn post_flags_changed(keycode: u16, flags: u64) -> Result<()> {
    let event = CGEvent::new_keyboard_event(None, keycode, flags != 0)
        .ok_or_else(|| PlatformError::Other("CGEventCreateKeyboardEvent failed".into()))?;
    CGEvent::set_type(Some(&event), CGEventType::FlagsChanged);
    CGEvent::set_flags(Some(&event), CGEventFlags(flags));
    CGEvent::post(CGEventTapLocation::HIDEventTap, Some(&event));
    Ok(())
}

